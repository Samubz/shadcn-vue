import type { Color, HSBColor } from 'reka-ui'
import type { ComputedRef, InjectionKey, Ref } from 'vue'
import type { ColorPickerFormat } from './format'
import { convertToRgb, createContext, isValidColor, parseColor } from 'reka-ui'

/**
 * Shared state of a `ColorPicker`, provided by the root and injected by every part.
 *
 * Labelling rule (the root renders no element, so these attributes land on a part):
 * - `id` goes to the first field of a `ColorPickerInput` or `ColorPickerFields` mounted outside the popover
 *   (`hasInput` is true), and to the `ColorPickerTrigger` otherwise.
 * - The trigger's accessible name: with `ariaLabelledby`, it uses
 *   `aria-labelledby="<ariaLabelledby> <valueId>"`, where `valueId` is an
 *   sr-only span holding the current hex. Without it, it uses
 *   `aria-label="<hex>"`; consumers add a label through `aria-labelledby`.
 * - `ariaDescribedby` goes on whichever control gets `id`.
 */
export interface ColorPickerContext {
  /**
   * The single shared color state, always in the `hsb` space with `alpha: 1`.
   * Pass it to reka primitives as `:model-value`; write it only through `setColor`.
   */
  color: Readonly<Ref<HSBColor>>
  /** `color` as a lowercase `#rrggbb` string. */
  hex: ComputedRef<string>
  /**
   * Replaces the shared color (normalized with `toSafeColor`, keeping the
   * current hue when the new color is achromatic) and emits
   * `update:modelValue` with the new hex when it changed.
   */
  setColor: (next: Color) => void
  /** Whether every part is disabled. */
  disabled: Readonly<Ref<boolean>>
  /**
   * The `id` given to `ColorPicker`, for a `<label for>` to target. Applied to
   * the `ColorField` input when `hasInput` is true, else to the trigger.
   */
  id: Readonly<Ref<string | undefined>>
  /** The `aria-labelledby` given to `ColorPicker`, passed through to the trigger's name. */
  ariaLabelledby: Readonly<Ref<string | undefined>>
  /** The `aria-describedby` given to `ColorPicker`, applied with `id`. */
  ariaDescribedby: Readonly<Ref<string | undefined>>
  /**
   * A stable id (reka `useId`, generated by the root) for the sr-only span
   * that holds the current hex, referenced by the trigger's `aria-labelledby`.
   */
  valueId: string
  /** Whether at least one `ColorPickerInput` or `ColorPickerFields` is mounted outside the popover. */
  hasInput: Readonly<Ref<boolean>>
  /**
   * Called by `ColorPickerInput` and `ColorPickerFields` (outside the popover) in setup; returns the function to call on
   * unmount. Drives `hasInput`.
   */
  registerInput: () => () => void
  /**
   * The format shown by the mounted `ColorPickerFields`: the one registered or
   * changed last, or `"hex"` when none is mounted. `ColorPickerCopy` copies in
   * it when it has no `format` prop of its own.
   *
   * Presentation state only: the shown format (and `registerFormat`,
   * `lastShownFormat`) never changes what `update:modelValue` emits, which is
   * always lowercase `#rrggbb`.
   */
  shownFormat: Readonly<Ref<ColorPickerFormat>>
  /**
   * Called by `ColorPickerFields` on mount with its shown format; returns the
   * function to call on unmount (idempotent, like `registerInput`'s). While
   * several are registered, the one registered or changed last drives
   * `shownFormat` and `lastShownFormat`. Never emits anything.
   */
  registerFormat: (format: Readonly<Ref<ColorPickerFormat>>) => () => void
  /**
   * The last format any `ColorPickerFields` showed, `"hex"` until one has.
   * Kept by the root across unmounts, because reka's `PopoverContent` unmounts
   * its children on close: a remounted `ColorPickerFields` starts from
   * `defaultFormat ?? lastShownFormat`. Never changes what is emitted.
   */
  lastShownFormat: Readonly<Ref<ColorPickerFormat>>
}

const [injectContext, provideColorPickerContext] = createContext<ColorPickerContext>('ColorPicker')

export { provideColorPickerContext }

/**
 * Marks the subtree of a `ColorPickerContent`, which provides `true`.
 *
 * A `ColorPickerInput` that injects `true` sits inside the popover, so it:
 * - renders a `ColorPickerSwatch` instead of a `ColorPickerTrigger` (a
 *   trigger there would re-anchor and toggle the popover);
 * - does not call `registerInput`, so it is not the picker's input;
 * - does not take `id` / `aria-describedby`.
 */
export const COLOR_PICKER_CONTENT_KEY: InjectionKey<boolean> = Symbol('ColorPickerContent')

/**
 * Injects the `ColorPicker` context. Throws an error naming `part` when it is
 * used outside a `ColorPicker`.
 */
export function injectColorPickerContext(part: string): ColorPickerContext {
  const context = injectContext(null)
  if (!context)
    throw new Error(`<${part}> must be used within <ColorPicker>`)
  return context
}

/** The initial color when neither `modelValue` nor `defaultValue` is valid: `#000000`. */
export const DEFAULT_COLOR: Readonly<HSBColor> = Object.freeze({
  space: 'hsb',
  h: 0,
  s: 0,
  b: 0,
  alpha: 1,
})

const COLOR_SPACES = new Set(['rgb', 'hsl', 'hsb'])

function clamp(value: number, min: number, max: number) {
  return Math.min(max, Math.max(min, value))
}

function isColor(value: unknown): value is Color {
  return typeof value === 'object'
    && value !== null
    && COLOR_SPACES.has((value as { space?: unknown }).space as string)
}

/**
 * Normalizes a color string or reka `Color` into the picker's state shape:
 * `hsb` space, `h` in 0..360, `s` and `b` in 0..100, `alpha` forced to 1.
 *
 * - Strings are accepted only when reka's `isValidColor` accepts them
 *   (`#rgb`, `#rrggbb`, `#rrggbbaa`, comma `rgb()`/`hsl()`/`hsb()`).
 * - Anything else (other strings, non-finite channels, other types) returns
 *   `fallback` unchanged.
 * - When the result is achromatic (saturation or brightness 0), it keeps
 *   `fallback.h`, so a gray does not reset the hue.
 *
 * Never throws and never logs.
 */
export function toSafeColor(value: unknown, fallback: HSBColor): HSBColor {
  let color: Color
  if (typeof value === 'string') {
    if (!isValidColor(value))
      return fallback
    color = parseColor(value)
  }
  else if (isColor(value)) {
    color = value
  }
  else {
    return fallback
  }

  let hsb: HSBColor
  try {
    hsb = toHsb(color)
  }
  catch {
    return fallback
  }
  if (![hsb.h, hsb.s, hsb.b].every(Number.isFinite))
    return fallback

  const s = clamp(hsb.s, 0, 100)
  const b = clamp(hsb.b, 0, 100)
  const h = s === 0 || b === 0
    ? fallback.h
    : hsb.h >= 0 && hsb.h <= 360 ? hsb.h : ((hsb.h % 360) + 360) % 360
  return { space: 'hsb', h, s, b, alpha: 1 }
}

/**
 * Any reka `Color` in the `hsb` space. An HSB color is returned as is;
 * others go through RGB with reui's formula rather than reka's
 * `convertToHsb`, whose hue carries float noise (36.24999999999999 for
 * 36.25) that `formatColor` would round the other way from reui. A gray
 * gets hue 0. Throws for an unknown space, like `convertToRgb`.
 */
export function toHsb(color: Color): HSBColor {
  if (color.space === 'hsb')
    return color
  const { r: red, g: green, b: blue, alpha } = convertToRgb(color)
  const r = red / 255
  const g = green / 255
  const b = blue / 255
  const max = Math.max(r, g, b)
  const delta = max - Math.min(r, g, b)
  let h = 0
  if (delta > 1e-9) {
    h = max === r
      ? ((g - b) / delta) % 6
      : max === g
        ? (b - r) / delta + 2
        : (r - g) / delta + 4
    h = ((h * 60 % 360) + 360) % 360
  }
  return { space: 'hsb', h, s: max === 0 ? 0 : (delta / max) * 100, b: max * 100, alpha }
}

/** Any reka `Color` as a lowercase `#rrggbb` string, ignoring alpha. */
export function toHex(color: Color): string {
  const { r, g, b } = convertToRgb(color)
  return `#${[r, g, b]
    .map(channel => Math.round(clamp(channel, 0, 255)).toString(16).padStart(2, '0'))
    .join('')}`
}
